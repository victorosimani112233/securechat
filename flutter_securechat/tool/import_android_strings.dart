Map<String, String> _parse(String xml) {
  final values = <String, String>{};
  final pattern = RegExp(r'<string\s+name="([^"]+)"[^>]*>([\s\S]*?)</string>');
  for (final match in pattern.allMatches(xml)) {
    values[match.group(1)!] = _decodeXml(match.group(2)!.trim());
  }
  return values;
}

String _decodeXml(String value) => value
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&quot;', '"')
    .replaceAll('&apos;', "'")
    .replaceAll('&amp;', '&')
    .replaceAll(r"\'", "'");

_Converted _convertPlaceholders(String value) {
  final placeholders = <String, Object?>{};
  final converted = value.replaceAllMapped(RegExp(r'%(\d+)\$([ds])'), (match) {
    final name = 'arg${match.group(1)}';
    placeholders[name] = {'type': match.group(2) == 'd' ? 'num' : 'String'};
    return '{$name}';
  });
  return _Converted(converted, placeholders);
}

class _Converted {
  const _Converted(this.text, this.placeholders);
  final String text;
  final Map<String, Object?> placeholders;
}
