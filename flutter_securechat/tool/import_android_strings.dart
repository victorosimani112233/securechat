import 'dart:convert';
import 'dart:io';

/// Mechanically imports the unchanged Kotlin Android string catalog into ARB.
/// Run from flutter_securechat/: dart tool/import_android_strings.dart
void main() {
  final sourceRoot = Directory('../app/src/main/res');
  if (!sourceRoot.existsSync()) {
    stderr.writeln('Android resource directory was not found.');
    exitCode = 2;
    return;
  }
  final locales = <String, String>{
    'en': 'values-en/strings.xml',
    'tr': 'values/strings.xml',
    'de': 'values-de/strings.xml',
    'ar': 'values-ar/strings.xml',
  };
  final output = Directory('lib/l10n')..createSync(recursive: true);
  for (final entry in locales.entries) {
    final strings = _parse(
      File('${sourceRoot.path}/${entry.value}').readAsStringSync(),
    );
    strings.addAll(_flutterAdditions[entry.key]!);
    final arb = <String, Object?>{'@@locale': entry.key};
    for (final item in strings.entries) {
      final converted = _convertPlaceholders(item.value);
      arb[item.key] = converted.text;
      if (converted.placeholders.isNotEmpty) {
        arb['@${item.key}'] = {
          'description': 'Migrated from Android string ${item.key}.',
          'placeholders': converted.placeholders,
        };
      }
    }
    File('${output.path}/app_${entry.key}.arb').writeAsStringSync(
      const JsonEncoder.withIndent('  ').convert(arb) + '\n',
      flush: true,
    );
  }
}

